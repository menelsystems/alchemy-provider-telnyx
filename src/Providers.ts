export class Providers extends Provider.ProviderCollection<Providers>()("Telnyx") {}

export type ProviderRequirements = Layer.Services<ReturnType<typeof providers>>;

export interface ProvidersOptions {
  /**
   * Credentials layer. Defaults to the Alchemy AuthProvider: `TELNYX_API_KEY`
   * (and optional `TELNYX_API_BASE_URL`) from the environment, else the
   * selected Alchemy profile (`alchemy profile edit`).
   */
  readonly credentials?: Layer.Layer<Credentials.Credentials>;
  /** HTTP client layer. Defaults to the stack's own. */
  readonly httpClient?: Layer.Layer<HttpClient.HttpClient>;
}

